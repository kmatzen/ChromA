def _compile(atlas):
    """Slice each entry's 64-character art into eight 8-pixel rows.

    The art is written as eight adjacent string literals, which Python joins
    into one 64-character string -- so it reads as a picture in the source and
    needs no per-row punctuation to keep aligned.
    """
    table = {}
    for art, ch in atlas:
        if len(art) != TILE * TILE:
            raise ValueError(f"glyph {ch!r} has {len(art)} pixels, want 64")
        bits = tuple(
            sum(1 << (7 - x) for x in range(TILE)
                if art[y * TILE + x] == "#")
            for y in range(TILE)
        )
        table[bits] = ch
    return table


GLYPHS = _compile(ATLAS)


def tile_bits(px, tx, ty, threshold=128):
    """The eight row bytes of the tile at (tx, ty), MSB-left, ink = set."""
    return tuple(
        sum(1 << (7 - x) for x in range(TILE)
            if px[tx * TILE + x, ty * TILE + y] < threshold)
        for y in range(TILE)
    )


def decode_screen(img, unknown=None):
    """Decode a 160x144 screen into its text lines.

    Unknown glyphs decode as '?'; if `unknown` is a list, their bitmaps are
    appended to it so the caller can report what needs adding rather than
    silently mangling a diagnostic.
    """
    img = img.convert("L")
    px = img.load()
    w, h = img.size
    lines = []
    for ty in range(h // TILE):
        row = []
        for tx in range(w // TILE):
            bits = tile_bits(px, tx, ty)
            if not any(bits):
                row.append(" ")
                continue
            ch = GLYPHS.get(bits)
            if ch is None:
                row.append("?")
                if unknown is not None and bits not in unknown:
                    unknown.append(bits)
            else:
                row.append(ch)
        lines.append("".join(row).rstrip())
    # Trim leading/trailing blank lines but keep interior ones: the gap
    # between "Registers" and "Assertions" is part of the layout.
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return lines


def render_bitmap(bits):
    """An unknown glyph as ASCII art, ready to paste into ATLAS."""
    return "\n".join(
        "".join("#" if b >> (7 - x) & 1 else "." for x in range(TILE))
        for b in bits
    )
