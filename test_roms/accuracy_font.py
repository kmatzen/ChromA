"""Glyph atlas for the text the accuracy ROMs print on screen.

The Mooneye and Blargg ROMs draw their diagnostics with an 8x8 tile font on
the Game Boy's 20x18 tile grid, in pure black on white.  That makes reading
them a dictionary lookup rather than OCR: hash the eight rows of a tile and
look the bitmap up here.

The atlas was harvested from the committed reference screens in
baselines/accuracy/ -- 49 screens produce only 56 distinct non-blank tiles --
and labelled by hand.  Two faces are present: a 6px proportional face used for
headings and register dumps, and a 7px bold face used for the banners some
Blargg ROMs draw.  Both sit on the same grid, so both decode the same way and
no caller has to care which is which.

The glyphs are kept as ASCII art rather than hex because that is the form a
human can check against the screen; ATLAS is compiled to a bitmap dict at
import.  Duplicate shapes between the two faces are fine -- they map to the
same character.

dump_diagnostics.py renders a screen and calls decode_screen() on it.  A glyph
that is not here decodes as '?' rather than being guessed at, and the caller
can ask for the unknown bitmaps so they can be added.
"""

