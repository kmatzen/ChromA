static const int FIRST_GBC_PALETTE = 49;

/* MBC1 multicart detection (issue #50).
 *
 * A multicart does not declare itself: its cartridge type byte is a plain
 * MBC1, and the difference is only in how the mapper is wired -- BANK1 is 4
 * bits instead of 5, so BANK2 shifts by 4 and picks one of four 256KB games
 * rather than one of four 512KB halves.
 *
 * So it has to be identified by content, the same way other emulators do it:
 * a 1MB ROM that carries a cartridge header at the start of each game, since
 * each game needs its own Nintendo logo to boot.  Comparing the logo at those
 * offsets against bank 0's own -- which is valid by definition, the cart
 * booted -- avoids embedding a second copy of the logo table here.
 */
int IsMbc1Multicart(const u8 *rom)
{
	int i;

	/* 0x05 is 1MB; a 4x256KB multicart cannot be any other size. */
	if (rom[0x0148] != 0x05)
	{
		return 0;
	}

	for (i = 0; i < 0x30; i++)
	{
		if (rom[0x40104 + i] != rom[0x0104 + i])
		{
			return 0;
		}
		if (rom[0x80104 + i] != rom[0x0104 + i])
		{
			return 0;
		}
	}
	return 1;
}

/* The CGB boot ROM only colorises Nintendo-licensed carts (issue #154).
 *
 * The title-hash table below is keyed on a one-byte checksum of the title, so
 * collisions with third-party titles are inevitable -- and hardware never hits
 * them, because the boot ROM gates the whole lookup on the licensee first.
 * From the boot ROM (ISSOtm/gb-bootroms, src/cgb.asm):
 *
 *	ld hl, HeaderOldLicensee	; $014B
 *	ld a, [hl]
 *	cp $33
 *	jr nz, .usingOldLicensee
 *	ld l, LOW(HeaderNewLicensee)	; $0144
 *	ld e, "0"
 *	ld a, [hli]
 *	cp e
 *	jr nz, .useDefaultIndex
 *	inc e				; "1"
 *	jr .checkMadeByNintendo
 *	.usingOldLicensee
 *	ld l, LOW(HeaderOldLicensee)
 *	ld e, 1
 *	.checkMadeByNintendo
 *	ld a, [hli]
 *	cp e
 *	jr nz, .useDefaultIndex
 *
 * So: old licensee $33 defers to the new licensee, which must be ASCII "01";
 * any other old licensee must itself be $01.  Failing the check takes the
 * .useDefaultIndex path, which is palette 0 -- the same value this function
 * already returns for a title that misses the table.
 *
 * Measured over test_roms/: every Nintendo title in the bundle passes the gate
 * and keeps its palette, and Mega Man - Dr. Wily's Revenge (old licensee $08,
 * Capcom) stops receiving palette 88 by title-hash collision.
 */
static int IsNintendoLicensed(const u8 *rom)
{
	if (rom[0x014B] == 0x33)
	{
		return rom[0x0144] == '0' && rom[0x0145] == '1';
	}
	return rom[0x014B] == 0x01;
}

int GetGbcPaletteNumber(u8 *rom)
{
	int entryCount = ARRSIZE(gameHashTable);
	int nameSum = 0;

	if (!IsNintendoLicensed(rom))
	{
		return 0;
	}

	for (int i = 0; i < 16; i++)
	{
		nameSum += rom[0x0134 + i];
	}
	int fourthLetter = rom[0x0134 + 3];
	nameSum &= 0xFF;
	int gameNumber = 0;
	for (int i = 0; i < entryCount; i+=2)
	{
		int hash = gameHashTable[i];
		int disambig = gameHashTable[i+1];
		if (hash == 0)
		{
			gameNumber++;
		}
		else if (hash == nameSum)
		{
			if (disambig == 0 || disambig == fourthLetter)
			{
				return gameNumber + FIRST_GBC_PALETTE;
			}
		}
	}
	return 0;
}
